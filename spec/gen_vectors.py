    def build_over_cap(self) -> None:
        d = self.det_gas
        t1 = self.tag(1, self.gen, 1500, 1500, d)
        t2 = self.tag(2, t1.tag_hash, 3000, 4500, d)
        t3 = self.tag(3, t2.tag_hash, 1000, 5500, d)
        caps = [2000, 5000, 2000]  # v1, v2 Storm Mode, v3 closed
        steps, settled = [], []
        for tag, expected in ((t1, False), (t2, False), (t3, True)):
            settled.append(tag)
            assert rules.over_cap(settled, caps) == expected
            steps.append({"tag": vec(tag), "over_cap": expected})
        self.out["over_cap"].append({"name": "r4_storm_cap_then_over", "caps": caps, "steps": steps})

