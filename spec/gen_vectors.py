#!/usr/bin/env python3
"""Generate spec/vectors.json (spec §20) from fixed test keys.

Run from the repo root with the server package installed:

    server/.venv/bin/python spec/gen_vectors.py

Signing is deterministic (RFC 6979), so rerunning produces the same file
byte for byte; server/tests/test_vectors.py fails if the committed file is
stale. Every expected outcome below is asserted against the library before it
is written, so a vector can't silently disagree with the code.

TEST KEYS ONLY. These private scalars are public; never use them outside tests.
"""

